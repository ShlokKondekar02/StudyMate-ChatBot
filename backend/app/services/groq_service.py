"""Groq LLM Service using the official Groq Python SDK."""

import logging
from typing import List, Optional
from groq import Groq, RateLimitError, AuthenticationError, APIConnectionError, APIStatusError, GroqError
from app.config import settings
from app.schemas import ChatMessage

logger = logging.getLogger("studymate.groq_service")


class GroqConfigurationError(Exception):
    """Raised when Groq API key is missing or unconfigured."""
    pass


class GroqService:
    """Encapsulates interaction with Groq LLM API."""

    def __init__(self):
        self._client: Optional[Groq] = None

    def _get_client(self) -> Groq:
        """Get or initialize Groq client instance."""
        # Always check latest settings state
        if not settings.is_groq_configured:
            raise GroqConfigurationError(
                "Groq API key is not configured. Please add your GROQ_API_KEY to the backend/.env file "
                "(e.g., GROQ_API_KEY=gsk_...) and restart or refresh. You can obtain a free API key at "
                "https://console.groq.com/keys"
            )

        # Lazy initialize or reinitialize if key changed
        if self._client is None or getattr(self._client, "_api_key", None) != settings.groq_api_key:
            self._client = Groq(api_key=settings.groq_api_key)

        return self._client

    def generate_chat_response(
        self,
        message: str,
        history: Optional[List[ChatMessage]] = None,
        temperature: float = 0.7,
    ) -> dict:
        """
        Send chat prompt to Groq API using configured Llama model.

        Args:
            message: Current user message.
            history: Optional list of previous messages in the conversation.
            temperature: Sampling temperature (0.0 to 2.0).

        Returns:
            dict containing 'response' and 'model'
        """
        client = self._get_client()
        model_name = settings.groq_model or "llama-3.3-70b-versatile"

        # Construct message payload with academic system instructions
        messages_payload = [
            {"role": "system", "content": settings.system_prompt}
        ]

        # Append conversation history if provided
        if history:
            for item in history:
                messages_payload.append({
                    "role": item.role,
                    "content": item.content
                })

        # Append current user prompt
        messages_payload.append({
            "role": "user",
            "content": message
        })

        try:
            logger.info("Dispatching completion request to Groq model: %s", model_name)
            completion = client.chat.completions.create(
                model=model_name,
                messages=messages_payload,
                temperature=temperature,
                max_completion_tokens=settings.max_tokens,
            )

            assistant_reply = completion.choices[0].message.content
            if not assistant_reply:
                assistant_reply = "No response was generated by the model. Please try asking again."

            return {
                "response": assistant_reply,
                "model": model_name
            }

        except RateLimitError as e:
            logger.warning("Groq rate limit encountered: %s", str(e))
            raise RuntimeError(
                "Groq API rate limit reached. Please wait a few seconds before sending another message."
            ) from e

        except AuthenticationError as e:
            logger.error("Groq authentication failure: %s", str(e))
            raise RuntimeError(
                "Invalid Groq API key. Please verify the GROQ_API_KEY value in your backend/.env file."
            ) from e

        except APIConnectionError as e:
            logger.error("Groq connection error: %s", str(e))
            raise RuntimeError(
                "Unable to connect to the Groq API server. Please check your internet connection."
            ) from e

        except APIStatusError as e:
            logger.error("Groq API status error: code=%s, message=%s", e.status_code, e.message)
            raise RuntimeError(
                f"Groq API returned an error (status {e.status_code}): {e.message}"
            ) from e

        except GroqError as e:
            logger.error("Generic Groq error: %s", str(e))
            raise RuntimeError(f"Groq API error occurred: {str(e)}") from e

        except Exception as e:
            logger.exception("Unexpected error during Groq chat completion")
            raise RuntimeError(f"Unexpected error: {str(e)}") from e


# Singleton service instance
groq_service = GroqService()
